const fs = require('fs');
const path = require('path');
const { loadPublishedCourses } = require('./lib/content-models');

const directory = loadPublishedCourses().map(course => ({
  slug: course.slug,
  title: course.title,
  lessons: course.modules.map(module => ({ slug: module.slug, title: module.title })),
}));
const output = '// Generated by scripts/generate-course-directory.js. Contains no lesson bodies.\n'
  + `export const COURSE_LESSON_DIRECTORY = ${JSON.stringify(directory, null, 2)} as const;\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'app', 'models', 'course-lesson-directory.ts'), output);
console.log(`Generated lesson directory: ${directory.length} courses, ${directory.reduce((sum, course) => sum + course.lessons.length, 0)} lessons.`);
